"""
Conflict-dependent block-encoding scan.

Varies the pairwise conflict of two controlled mass vectors and measures the
actual post-selection success probability of the circuit-executed ER step.
This replaces a stored/interpolated kappa curve with a quantity generated by
the block-encoding circuit itself.
"""

import os

import numpy as np

from core.block_encoding import ERBlockEncoding
from core.mitigation import conflict_coefficient

LEGACY_PAPER_KAPPA = np.array([5.23, 53.08, 478.15])
LEGACY_PAPER_CONFLICT = np.array([0.10, 0.50, 0.90])


def main():
    N = 3
    be = ERBlockEncoding(N=N)
    singletons = np.linspace(0.1, 0.95, 9)
    rows = []
    print("=" * 72)
    print("Conflict-dependent post-selection scan (circuit-executed)")
    print("=" * 72)
    print(f"  {'a':>6}  {'conflict':>10}  {'K':>8}  {'p_success':>10}  "
          f"{'1/p overhead':>13}")
    for a in singletons:
        # Two valid mass vectors: singleton on different grades + residual D.
        m_I = np.array([a, 0.0, 0.0, 1.0 - a, 0.0])
        m_next = np.array([0.0, a, 0.0, 1.0 - a, 0.0])
        c = conflict_coefficient(m_I, m_next)
        K = 1.0 / (1.0 - c)
        result = be.step(m_I, m_next)
        p = result['success_probability']
        rows.append((a, c, K, p, 1.0 / p))
        print(f"  {a:>6.2f}  {c:>10.4f}  {K:>8.3f}  {p:>10.4f}  "
              f"{1.0 / p:>13.3f}")

    print("\n[Legacy reference kappa values, not used for current claims]")
    print(f"  {'K_conf':>8}  {'legacy kappa':>12}")
    for c, kappa in zip(LEGACY_PAPER_CONFLICT, LEGACY_PAPER_KAPPA):
        print(f"  {c:>8.2f}  {kappa:>12.2f}")
    print("  The circuit produces a conflict-dependent success probability;")
    print("  the spectral condition number of the fixed B is data-independent.")

    out_dir = os.path.join(os.path.dirname(__file__), '..', 'outputs', 'logs')
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, 'conflict_scan.npz')
    np.savez(out_path, rows=np.array(rows))
    print(f"\nSaved: {out_path}")


if __name__ == '__main__':
    main()
