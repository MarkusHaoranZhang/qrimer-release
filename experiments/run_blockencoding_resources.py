"""
Resource table for the executable block-encoding circuit.

The table reports actual transpiled depth and gate count of one block-encoded
ER step for N=3..10 on {u, cx}.  This is the dense validation construction;
it is not the paper's sparse/fault-tolerant circuit, but the numbers are
generated by code rather than copied from the manuscript.
"""

import time

import numpy as np
from qiskit import QuantumCircuit, transpile
from qiskit.circuit.library import UnitaryGate

from core.block_encoding import HermitianERBlockEncoding
from core.qer import QER


def main():
    print("=" * 82)
    print("Block-encoding resource table (one ER step, {u, cx} transpilation)")
    print("=" * 82)
    print(f"  {'N':>3}  {'qubits':>6}  {'raw depth':>9}  {'transpiled depth':>16}  "
          f"{'gates':>9}  {'time(s)':>8}")
    for N in list(range(3, 13)) + [15, 20]:
        be = HermitianERBlockEncoding(N)
        qer = QER(N=N, L=2, kappa_max=50.0)
        rng = np.random.default_rng(N)
        betas = rng.dirichlet(np.ones(N), size=2) * 0.9
        w = np.array([0.5, 0.5])
        m_I = qer._mass_vector(w[0], betas[0])
        m_next = qer._mass_vector(w[1], betas[1])
        psi, _ = be._prepare_input(m_I, m_next)

        qc = QuantumCircuit(be.n_total)
        qc.append(UnitaryGate(be._prep_unitary(psi), label='Prep'),
                  range(be.n_total))
        qc.append(UnitaryGate(be.U, label='U_BE'), range(be.n_total))

        t0 = time.perf_counter()
        trans = transpile(qc, basis_gates=['u', 'cx'], optimization_level=0)
        elapsed = time.perf_counter() - t0
        print(f"  {N:>3}  {qc.num_qubits:>6}  {qc.depth():>9}  "
              f"{trans.depth():>16}  {trans.size():>9}  {elapsed:>8.2f}")


if __name__ == '__main__':
    main()
